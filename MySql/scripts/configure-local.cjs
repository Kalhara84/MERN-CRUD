const fs = require('fs');
const crypto = require('crypto');
const path = require('path');
const root = path.join(__dirname, '..');
const file = path.join(root, 'backend/.env');
const backup = file + '.postgresql.backup';
if (!fs.existsSync(backup)) fs.copyFileSync(file, backup);
const secret = () => crypto.randomBytes(24).toString('hex');
fs.writeFileSync(file, `PORT=5000\nDB_HOST=127.0.0.1\nDB_PORT=3307\nDB_NAME=srtbf_farm\nDB_USER=root\nDB_PASSWORD=${secret()}\nJWT_SECRET=${secret()}\nFRONTEND_URL=http://localhost:5174\nADMIN_CODE=ADMIN\nADMIN_PASSWORD=${secret()}\n`);
console.log('Local MySQL configuration saved. Original configuration backed up privately.');
